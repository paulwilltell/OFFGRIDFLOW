func sectionTitle(pdf *gofpdf.Fpdf, num, title string) {
	if pdf.GetY() > 245 {
		pdf.AddPage()
	}
	pdf.Ln(6)
	setFill(pdf, brandMid)
	y := pdf.GetY()
	pdf.Rect(marginX, y, 3, 7, "F")
	pdf.SetX(marginX + 6)
	pdf.SetFont("Helvetica", "B", 13.5)
	setColor(pdf, brandDark)
	pdf.CellFormat(0, 7, fmt.Sprintf("%s.  %s", num, title), "", 1, "L", false, 0, "")
	pdf.Ln(2)
}

func bodyText(pdf *gofpdf.Fpdf, txt string) {
	pdf.SetFont("Helvetica", "", 10)
	setColor(pdf, inkColor)
	pdf.MultiCell(usableW, 5.2, txt, "", "L", false)
	pdf.Ln(1.5)
}

func bulletText(pdf *gofpdf.Fpdf, txt string) {
	pdf.SetFont("Helvetica", "", 10)
	setColor(pdf, brandMid)
	pdf.SetX(marginX)
	pdf.CellFormat(5, 5.2, "-", "", 0, "L", false, 0, "")
	setColor(pdf, inkColor)
	pdf.MultiCell(usableW-5, 5.2, txt, "", "L", false)
}

func keyVal(pdf *gofpdf.Fpdf, k, v string) {
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "", 10)
	setColor(pdf, mutedColor)
	pdf.CellFormat(55, 6.5, k, "", 0, "L", false, 0, "")
	pdf.SetFont("Helvetica", "B", 10)
	setColor(pdf, inkColor)
	pdf.MultiCell(usableW-55, 6.5, v, "", "L", false)
}

func tableHead(pdf *gofpdf.Fpdf, headers []string, widths []float64) {
	if pdf.GetY() > 250 {
		pdf.AddPage()
	}
	pdf.SetFont("Helvetica", "B", 9)
	setFill(pdf, brandDark)
	pdf.SetTextColor(255, 255, 255)
	pdf.SetX(marginX)
	for i, h := range headers {
		align := "L"
		if i > 0 && i >= len(headers)-2 {
			align = "R"
		}
		pdf.CellFormat(widths[i], 7, h, "", 0, align, true, 0, "")
	}
	pdf.Ln(7)
}

func tableRow3(pdf *gofpdf.Fpdf, cells [3]string, widths []float64, zebra, total bool) {
	tableRowN(pdf, cells[:], widths, zebra, total)
}

func tableRowN(pdf *gofpdf.Fpdf, cells []string, widths []float64, zebra, total bool) {
	rowH := 6.5
	if pdf.GetY()+rowH > 275 {
		pdf.AddPage()
	}
	fill := false
	if total {
		pdf.SetFont("Helvetica", "B", 9)
		setFill(pdf, [3]int{234, 240, 236})
		fill = true
	} else {
		pdf.SetFont("Helvetica", "", 9)
		if zebra {
			setFill(pdf, zebraColor)
			fill = true
		}
	}
	setColor(pdf, inkColor)
	pdf.SetX(marginX)
	for i, c := range cells {
		align := "L"
		if i > 0 && i >= len(cells)-2 {
			align = "R"
		}
		pdf.CellFormat(widths[i], rowH, c, "", 0, align, fill, 0, "")
	}
	pdf.Ln(rowH)
}

