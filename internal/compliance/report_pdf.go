package compliance

// report_pdf.go renders an InventoryReport into an audit-ready, assurance-grade
// PDF structured for California SB 253 / the GHG Protocol Corporate Standard.
// Every figure in the report traces to the activity-data and emission-factor
// tables it contains, so a third-party assurer can verify it.

import (
	"bytes"
	"fmt"
	"strings"
	"time"

	"github.com/jung-kurt/gofpdf"
)

// Brand palette (forest green).
var (
	brandDark  = [3]int{29, 59, 46}   // #1d3b2e
	brandMid   = [3]int{47, 107, 80}  // #2f6b50
	inkColor   = [3]int{22, 32, 27}   // #16201b
	mutedColor = [3]int{106, 122, 113} // #6a7a71
	lineColor  = [3]int{221, 227, 222} // #dde3de
	zebraColor = [3]int{247, 248, 246} // #f7f8f6
)

const (
	pageW   = 210.0
	marginX = 15.0
	usableW = pageW - 2*marginX
)

// ExportInventoryReportPDF renders the full report and returns the PDF bytes.
func ExportInventoryReportPDF(inv *InventoryReport) ([]byte, error) {
	orgName := inv.OrgName
	if strings.TrimSpace(orgName) == "" {
		orgName = "Your Organization"
	}

	pdf := gofpdf.New("P", "mm", "A4", "")
	pdf.SetTitle(fmt.Sprintf("GHG Emissions Inventory %d - %s", inv.Year, orgName), false)
	pdf.SetAuthor("OffGridFlow", false)
	pdf.AliasNbPages("")
	pdf.SetMargins(marginX, 18, marginX)
	pdf.SetAutoPageBreak(true, 20)

	// Repeating footer on every page.
	pdf.SetFooterFunc(func() {
		pdf.SetY(-15)
		pdf.SetFont("Helvetica", "", 7.5)
		setColor(pdf, mutedColor)
		pdf.CellFormat(0, 5, fmt.Sprintf("Generated by OffGridFlow  |  %s  |  GHG Protocol Corporate Standard  |  %s",
			orgName, inv.GeneratedAt.Format("2 Jan 2006")), "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 5, fmt.Sprintf("Page %d of {nb}", pdf.PageNo()), "", 0, "R", false, 0, "")
	})

	renderCover(pdf, inv, orgName)

	// Content pages start here.
	pdf.AddPage()
	renderEntity(pdf, inv, orgName)
	renderExecutiveSummary(pdf, inv)
	renderMethodology(pdf, inv)
	renderByCategory(pdf, inv)
	renderByLocation(pdf, inv)
	renderFactors(pdf, inv)
	renderActivityData(pdf, inv)
	renderDataQuality(pdf, inv)
	renderAssurance(pdf, inv, orgName)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("pdf export: %w", err)
	}
	return buf.Bytes(), nil
}

