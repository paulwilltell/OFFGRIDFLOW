func setColor(pdf *gofpdf.Fpdf, c [3]int) { pdf.SetTextColor(c[0], c[1], c[2]) }
func setFill(pdf *gofpdf.Fpdf, c [3]int)  { pdf.SetFillColor(c[0], c[1], c[2]) }
func setDraw(pdf *gofpdf.Fpdf, c [3]int)  { pdf.SetDrawColor(c[0], c[1], c[2]) }

// fmtT formats tonnes with thousands separators and 2 decimals.
func fmtT(f float64) string { return withCommas(fmt.Sprintf("%.2f", f)) }

// fmtNum formats a quantity, dropping trailing zeros for whole numbers.
func fmtNum(f float64) string {
	if f == float64(int64(f)) {
		return withCommas(fmt.Sprintf("%d", int64(f)))
	}
	return withCommas(fmt.Sprintf("%.2f", f))
}

func withCommas(s string) string {
	neg := strings.HasPrefix(s, "-")
	s = strings.TrimPrefix(s, "-")
	intPart, frac := s, ""
	if i := strings.IndexByte(s, '.'); i >= 0 {
		intPart, frac = s[:i], s[i:]
	}
	n := len(intPart)
	if n <= 3 {
		return sign(neg) + intPart + frac
	}
	var b strings.Builder
	pre := n % 3
	if pre > 0 {
		b.WriteString(intPart[:pre])
		if n > pre {
			b.WriteByte(',')
		}
	}
	for i := pre; i < n; i += 3 {
		b.WriteString(intPart[i : i+3])
		if i+3 < n {
			b.WriteByte(',')
		}
	}
	return sign(neg) + b.String() + frac
}

func sign(neg bool) string {
	if neg {
		return "-"
	}
	return ""
}

func pct(part, whole float64) string {
	if whole == 0 {
		return "0%"
	}
	return fmt.Sprintf("%.1f%%", part/whole*100)
}

func titleCase(s string) string {
	s = strings.ReplaceAll(strings.ReplaceAll(s, "_", " "), "-", " ")
	words := strings.Fields(s)
	for i, w := range words {
		if len(w) > 0 {
			words[i] = strings.ToUpper(w[:1]) + w[1:]
		}
	}
	if len(words) == 0 {
		return s
	}
	return strings.Join(words, " ")
}

func truncStr(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n-1] + "..."
}

func factorUnit(f FactorRef) string {
	if f.Unit == "" {
		return "per unit"
	}
	return "kg/" + f.Unit
}

func orNoun(orgName string) string {
	if strings.TrimSpace(orgName) == "" {
		return "the organization"
	}
	return orgName
}

func shortID(id string) string {
	id = strings.ReplaceAll(id, "-", "")
	if len(id) > 8 {
		return strings.ToUpper(id[:8])
	}
	if id == "" {
		return "ORG"
	}
	return strings.ToUpper(id)
}
