func renderCover(pdf *gofpdf.Fpdf, inv *InventoryReport, orgName string) {
	pdf.AddPage()

	// Top brand band.
	setFill(pdf, brandDark)
	pdf.Rect(0, 0, pageW, 70, "F")
	pdf.SetY(24)
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "B", 12)
	pdf.SetTextColor(160, 210, 180)
	pdf.CellFormat(0, 7, "OFFGRIDFLOW  |  GHG EMISSIONS INVENTORY", "", 1, "L", false, 0, "")
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "B", 26)
	pdf.SetTextColor(255, 255, 255)
	pdf.CellFormat(0, 14, "Greenhouse Gas", "", 1, "L", false, 0, "")
	pdf.SetX(marginX)
	pdf.CellFormat(0, 14, "Emissions Inventory Report", "", 1, "L", false, 0, "")

	pdf.SetY(88)
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "", 11)
	setColor(pdf, mutedColor)
	pdf.CellFormat(0, 6, "Prepared for", "", 1, "L", false, 0, "")
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "B", 20)
	setColor(pdf, inkColor)
	pdf.CellFormat(0, 11, orgName, "", 1, "L", false, 0, "")

	pdf.Ln(6)
	coverRow(pdf, "Reporting period", fmt.Sprintf("1 January - 31 December %d", inv.Year))
	coverRow(pdf, "Reporting standard", "GHG Protocol Corporate Accounting & Reporting Standard")
	coverRow(pdf, "Regulatory basis", "California SB 253 - Climate Corporate Data Accountability Act")
	coverRow(pdf, "Report generated", inv.GeneratedAt.Format("2 January 2006, 15:04 MST"))

	// Headline total in a card.
	pdf.SetY(160)
	pdf.SetX(marginX)
	setFill(pdf, zebraColor)
	setDraw(pdf, lineColor)
	pdf.Rect(marginX, 160, usableW, 34, "FD")
	pdf.SetXY(marginX+8, 168)
	pdf.SetFont("Helvetica", "", 11)
	setColor(pdf, mutedColor)
	pdf.CellFormat(0, 6, "Total reported emissions", "", 1, "L", false, 0, "")
	pdf.SetXY(marginX+8, 175)
	pdf.SetFont("Helvetica", "B", 24)
	setColor(pdf, brandMid)
	pdf.CellFormat(0, 12, fmt.Sprintf("%s  tCO2e", fmtT(inv.TotalTonnes)), "", 1, "L", false, 0, "")

	pdf.SetY(210)
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "I", 8.5)
	setColor(pdf, mutedColor)
	pdf.MultiCell(usableW, 4.5, "This report presents a greenhouse gas emissions inventory prepared using the GHG Protocol Corporate Standard. Figures are self-reported based on activity data supplied by the organization and are structured to support third-party limited assurance as required under California SB 253. This document is not itself an assurance opinion.", "", "L", false)
}

func coverRow(pdf *gofpdf.Fpdf, label, value string) {
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "", 10)
	setColor(pdf, mutedColor)
	pdf.CellFormat(45, 7, label, "", 0, "L", false, 0, "")
	pdf.SetFont("Helvetica", "B", 10)
	setColor(pdf, inkColor)
	pdf.CellFormat(usableW-45, 7, value, "", 1, "L", false, 0, "")
}

func renderEntity(pdf *gofpdf.Fpdf, sec *int, inv *InventoryReport, orgName string) {
	sectionTitle(pdf, sec, "Reporting Entity & Organizational Boundaries")
	keyVal(pdf, "Reporting entity", orgName)
	keyVal(pdf, "Reporting period", fmt.Sprintf("1 January - 31 December %d", inv.Year))
	keyVal(pdf, "Consolidation approach", "Operational control")
	keyVal(pdf, "Reporting standard", "GHG Protocol Corporate Accounting & Reporting Standard (revised)")
	keyVal(pdf, "Gases covered", "CO2, CH4, N2O, HFCs, PFCs, SF6, NF3 (7 Kyoto gases), expressed as CO2e")
	bodyText(pdf, "The organizational boundary is defined using the operational control approach: emissions from operations over which the entity has the authority to introduce and implement its operating policies are consolidated at 100%. Emissions are classified into Scope 1 (direct), Scope 2 (purchased energy) and Scope 3 (value chain) in accordance with the GHG Protocol.")
}

func renderExecutiveSummary(pdf *gofpdf.Fpdf, sec *int, inv *InventoryReport) {
	sectionTitle(pdf, sec, "Executive Summary")
	bodyText(pdf, fmt.Sprintf("For the %d reporting year, %s and its consolidated operations reported total greenhouse gas emissions of %s tonnes of CO2 equivalent (tCO2e), disaggregated by scope below.", inv.Year, orNoun(inv.OrgName), fmtT(inv.TotalTonnes)))

	th := []string{"Scope", "Emissions (tCO2e)", "Share"}
	widths := []float64{90, 55, usableW - 145}
	tableHead(pdf, th, widths)
	rows := [][3]string{
		{"Scope 1 - Direct", fmtT(inv.Scope1Tonnes), pct(inv.Scope1Tonnes, inv.TotalTonnes)},
		{"Scope 2 - Energy indirect", fmtT(inv.Scope2Tonnes), pct(inv.Scope2Tonnes, inv.TotalTonnes)},
		{"Scope 3 - Value chain", fmtT(inv.Scope3Tonnes), pct(inv.Scope3Tonnes, inv.TotalTonnes)},
	}
	for i, r := range rows {
		tableRow3(pdf, r, widths, i%2 == 1, false)
	}
	tableRow3(pdf, [3]string{"Total", fmtT(inv.TotalTonnes), "100%"}, widths, false, true)
}

func renderScope1Gases(pdf *gofpdf.Fpdf, sec *int, inv *InventoryReport) {
	if inv.Scope1Tonnes <= 0 {
		return
	}
	g := inv.Scope1Gases
	sectionTitle(pdf, sec, "Scope 1 Emissions by Greenhouse Gas")
	bodyText(pdf, "The GHG Protocol requires the seven Kyoto gases to be reported. Scope 1 combustion emissions are disaggregated into CO2, CH4 and N2O below, expressed as CO2e using IPCC AR6 100-year GWPs (CH4 fossil = 29.8, N2O = 273). The industrial gases (HFCs, PFCs, SF6, NF3) arise from fugitive/process sources; none were reported in this inventory.")

	th := []string{"Greenhouse gas", "Emissions (tCO2e)", "Share of Scope 1"}
	widths := []float64{90, 45, usableW - 135}
	tableHead(pdf, th, widths)
	rows := [][3]string{
		{"Carbon dioxide (CO2)", fmtT(g.CO2), pct(g.CO2, inv.Scope1Tonnes)},
		{"Methane (CH4)", fmtT(g.CH4), pct(g.CH4, inv.Scope1Tonnes)},
		{"Nitrous oxide (N2O)", fmtT(g.N2O), pct(g.N2O, inv.Scope1Tonnes)},
		{"Hydrofluorocarbons (HFCs)", fmtT(g.HFCs), pct(g.HFCs, inv.Scope1Tonnes)},
		{"Perfluorocarbons (PFCs)", fmtT(g.PFCs), pct(g.PFCs, inv.Scope1Tonnes)},
		{"Sulfur hexafluoride (SF6)", fmtT(g.SF6), pct(g.SF6, inv.Scope1Tonnes)},
		{"Nitrogen trifluoride (NF3)", fmtT(g.NF3), pct(g.NF3, inv.Scope1Tonnes)},
	}
	for i, r := range rows {
		tableRow3(pdf, r, widths, i%2 == 1, false)
	}
	tableRow3(pdf, [3]string{"Total Scope 1 (fossil)", fmtT(g.Total()), "100%"}, widths, false, true)

	note := "The combustion split uses representative fossil-fuel gas shares (CO2-dominant); for third-party assurance, apply fuel- and technology-specific gas factors (EPA GHG Emission Factors Hub / IPCC)."
	if g.Biogenic > 0 {
		note += fmt.Sprintf(" Biogenic CO2 of %s tCO2e (from biofuels) is reported separately and excluded from the Scope 1 fossil total, per the GHG Protocol.", fmtT(g.Biogenic))
	} else {
		note += " No biogenic CO2 (from biofuels) was reported; it would be disclosed separately where present."
	}
	bodyText(pdf, note)
}

func renderScope2Dual(pdf *gofpdf.Fpdf, sec *int, inv *InventoryReport) {
	// Only meaningful when there is Scope 2 electricity in the inventory.
	if inv.Scope2Tonnes <= 0 {
		return
	}
	sectionTitle(pdf, sec, "Scope 2 Dual Reporting (Location & Market-Based)")
	bodyText(pdf, "The GHG Protocol Scope 2 Guidance requires purchased-electricity emissions to be reported under both methods: the location-based method (grid-average emission factors) and the market-based method (contractual instruments such as supplier-specific factors, renewable energy certificates, guarantees of origin, or power purchase agreements). Both are presented below.")

	th := []string{"Scope 2 method", "Emissions (tCO2e)"}
	widths := []float64{usableW - 55, 55}
	tableHead(pdf, th, widths)
	tableRowN(pdf, []string{"Location-based (grid average)", fmtT(inv.Scope2Tonnes)}, widths, false, false)
	tableRowN(pdf, []string{"Market-based (contractual)", fmtT(inv.Scope2MarketTonnes)}, widths, true, false)

	if inv.HasMarketData {
		reduction := inv.Scope2Tonnes - inv.Scope2MarketTonnes
		bodyText(pdf, fmt.Sprintf("Market-based emissions reflect the supplier/contractual emission factors and renewable coverage supplied per account, a reduction of %s tCO2e versus location-based. Offsets, if any, are excluded from both figures and disclosed separately.", fmtT(reduction)))
	} else {
		bodyText(pdf, "No contractual instruments (supplier-specific emission factors or renewable/REC coverage) were supplied for the reporting period; the market-based figure therefore equals the location-based figure. To reflect green procurement, provide a per-account supplier emission factor (kgCO2e/kWh) or a renewable share with your electricity data.")
	}
}

func renderMethodology(pdf *gofpdf.Fpdf, sec *int, inv *InventoryReport) {
	sectionTitle(pdf, sec, "Methodology")
	bodyText(pdf, "Emissions were quantified using the activity-based method defined by the GHG Protocol Corporate Standard: each activity's emissions equal its activity data multiplied by a published emission factor for the relevant scope, region and category.")

	pdf.SetFont("Helvetica", "B", 10)
	setColor(pdf, inkColor)
	pdf.CellFormat(0, 6, "Calculation formulae applied:", "", 1, "L", false, 0, "")
	bulletText(pdf, "General: Emissions (tCO2e) = Sum( Activity data x Emission factor x GWP ).")
	bulletText(pdf, "Scope 1 (combustion): Sum( Fuel consumed x Fuel emission factor ). Fuel-specific factors bundle CO2, CH4 and N2O expressed as CO2e.")
	bulletText(pdf, "Scope 2 (location-based): Sum( Electricity (kWh) x Grid-average emission factor ), using US EPA eGRID grid factors.")
	bulletText(pdf, "Scope 3 travel: Sum( Distance x Mode-specific factor ). Scope 3 spend: Sum( Spend x EEIO factor ).")

	pdf.Ln(1)
	keyVal(pdf, "Global Warming Potentials", "IPCC Sixth Assessment Report (AR6), 100-year time horizon (GWP-100)")
	keyVal(pdf, "Scope 2 methods", "Dual reporting: location-based and market-based (see Scope 2 Dual Reporting section)")
	bodyText(pdf, "Biofuels (e.g. biodiesel, ethanol, sustainably-sourced wood) are treated as carbon-neutral at the point of combustion per the GHG Protocol; biogenic CO2 is excluded from Scope 1 totals and reported separately where present. Emission factors are representative published values from the sources cited; for third-party assurance, confirm the specific factor vintage applicable to the reporting period.")

	if len(inv.Factors) > 0 {
		srcSet := map[string]bool{}
		var srcs []string
		for _, f := range inv.Factors {
			if !srcSet[f.Source] {
				srcSet[f.Source] = true
				srcs = append(srcs, f.Source)
			}
		}
		bodyText(pdf, "Emission factor sources used in this inventory: "+strings.Join(srcs, "; ")+". A complete factor-by-factor audit trail is provided in a later section.")
	}
}

