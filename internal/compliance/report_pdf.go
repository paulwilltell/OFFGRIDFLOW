func tableRow3(pdf *gofpdf.Fpdf, cells [3]string, widths []float64, zebra, total bool) {
	tableRowN(pdf, cells[:], widths, zebra, total)
}

func tableRowN(pdf *gofpdf.Fpdf, cells []string, widths []float64, zebra, total bool) {
	rowH := 6.5
	if pdf.GetY()+rowH > 275 {
		pdf.AddPage()
	}
	fill := false
	if total {
		pdf.SetFont("Helvetica", "B", 9)
		setFill(pdf, [3]int{234, 240, 236})
		fill = true
	} else {
		pdf.SetFont("Helvetica", "", 9)
		if zebra {
			setFill(pdf, zebraColor)
			fill = true
		}
	}
	setColor(pdf, inkColor)
	pdf.SetX(marginX)
	for i, c := range cells {
		align := "L"
		if i > 0 && i >= len(cells)-2 {
			align = "R"
		}
		pdf.CellFormat(widths[i], rowH, c, "", 0, align, fill, 0, "")
	}
	pdf.Ln(rowH)
}

