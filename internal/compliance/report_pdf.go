func sectionTitle(pdf *gofpdf.Fpdf, sec *int, title string) {
	*sec++
	if pdf.GetY() > 245 {
		pdf.AddPage()
	}
	pdf.Ln(6)
	setFill(pdf, brandMid)
	y := pdf.GetY()
	pdf.Rect(marginX, y, 3, 7, "F")
	pdf.SetX(marginX + 6)
	pdf.SetFont("Helvetica", "B", 13.5)
	setColor(pdf, brandDark)
	pdf.CellFormat(0, 7, fmt.Sprintf("%d.  %s", *sec, title), "", 1, "L", false, 0, "")
	pdf.Ln(2)
}

func bodyText(pdf *gofpdf.Fpdf, txt string) {
	pdf.SetFont("Helvetica", "", 10)
	setColor(pdf, inkColor)
	pdf.MultiCell(usableW, 5.2, txt, "", "L", false)
	pdf.Ln(1.5)
}

